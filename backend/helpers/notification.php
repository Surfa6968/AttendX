<?php

/*
|--------------------------------------------------------------------------
| Create Notification
|--------------------------------------------------------------------------
|
| Reusable helper for creating notifications.
|
*/

function createNotification(
    $mysqli,
    $userId,
    $title,
    $message,
    $notificationType = "System",
    $actionUrl = null
) {

    /*
    |--------------------------------------------------------------------------
    | SQL
    |--------------------------------------------------------------------------
    */

    $sql = "
        INSERT INTO notifications
        (
            user_id,
            title,
            message,
            notification_type,
            action_url,
            is_read
        )
        VALUES (?, ?, ?, ?, ?, 0)
    ";

    /*
    |--------------------------------------------------------------------------
    | Prepare
    |--------------------------------------------------------------------------
    */

    $stmt = mysqli_prepare($mysqli, $sql);

    if (!$stmt) {
        return false;
    }

    /*
    |--------------------------------------------------------------------------
    | Bind Parameters
    |--------------------------------------------------------------------------
    */

    mysqli_stmt_bind_param(
        $stmt,
        "issss",
        $userId,
        $title,
        $message,
        $notificationType,
        $actionUrl
    );

    /*
    |--------------------------------------------------------------------------
    | Execute
    |--------------------------------------------------------------------------
    */

    $result = mysqli_stmt_execute($stmt);

    /*
    |--------------------------------------------------------------------------
    | Close
    |--------------------------------------------------------------------------
    */

    mysqli_stmt_close($stmt);

    return $result;
}